async def test_reservations_never_exceed_budget_and_failed_retry_keeps_spend(engine):
    store = BackfillStore(engine)
    async with store.locked():
        await store.begin_batch(SINCE, 3600, False)
        await store.enqueue_page([record(1)], 1, SINCE)
        url = (await store.pending(1))[0]["url"]
        for _ in range(3):
            assert await store.reserve_attempt(url, 3)
        assert not await store.reserve_attempt(url, 3)
        await store.mark_existing()
        assert (await store.snapshot())["failed"] == 1
        await store.retry_failed()
        assert (await store.pending(1))[0]["attempts"] == 0
        assert (await store.snapshot())["today_attempts"] == 3
        assert not await store.reserve_attempt(url, 3)
        async with store.connection.begin():
            # Beijing date boundaries are produced in SQL, independent of machine timezone.
            stored = (
                await store.connection.execute(text("SELECT source,day FROM crawl_daily_budget"))
            ).one()
            today = (
                await store.connection.execute(
                    text("SELECT (NOW() AT TIME ZONE 'Asia/Shanghai')::date")
                )
            ).scalar_one()
            assert stored.source == SOURCE and stored.day == today


async def test_cooldown_and_initial_boundary_persist_without_operator_override(engine):
    store = BackfillStore(engine)
    async with store.locked():
        async with store.connection.begin():
            await store.connection.execute(
                text("""
                INSERT INTO posts(source_url,posted_at) VALUES('old',CAST(:date AS timestamptz))
            """),
                {"date": SINCE},
            )
        status, initial = await store.begin_batch(None, 3600, False)
        assert status == "ready"
        from datetime import timedelta

        assert initial["since_at"] == SINCE - timedelta(days=7)
        status, _ = await store.begin_batch(None, 3600, False)
        assert status == "cooldown"
        with pytest.raises(ValueError, match="persisted campaign"):
            await store.begin_batch(SINCE, 3600, False)
        assert (await store.snapshot())["since_at"] == initial["since_at"]



def record(index: int, *, timestamp=None):
    return {
        "contentId": str(index),
        "momentData": {
            "createdAt": timestamp or int(SINCE.timestamp() * 1000 + 86400000),
            "title": "面经",
        },
    }


@asynccontextmanager
async def browser():
    yield object()


async def release_cooldown(engine):
    async with engine.begin() as connection:
        await connection.execute(
            text("UPDATE crawl_progress SET last_batch_at=NOW()-INTERVAL '2 hours'")
        )


async def test_restart_dedupe_and_newest_pages_do_not_end_history_scan(engine, monkeypatch):
    scan = AsyncMock(side_effect=[[record(i) for i in range(start, 21)] for start in (1, 2, 3)])
    detail = AsyncMock(return_value=("Redis问题和完整正文", "面经"))
    monkeypatch.setattr(backfill, "fetch_tab_page", scan)
    monkeypatch.setattr(backfill, "fetch_detail", detail)
    first = await backfill.backfill_batch(
        since=SINCE,
        limits=backfill.BackfillLimits(batch=2),
        store=BackfillStore(engine),
        fetcher_factory=browser,
    )
    assert first["saved"] == 2 and first["pending"] == 18 and first["next_page"] == 4
    await release_cooldown(engine)
    second = await backfill.backfill_batch(store=BackfillStore(engine), fetcher_factory=browser)
    assert second["saved"] == 18 and second["today_attempts"] == 20
    assert scan.await_count == 3  # restart consumes persisted queue before discovery
    await release_cooldown(engine)
    scan.side_effect = [[record(1)], [record(2)], [record(21)]]
    third = await backfill.backfill_batch(store=BackfillStore(engine), fetcher_factory=browser)
    assert [call.args[0] for call in scan.await_args_list[-3:]] == [2, 3, 4]
    assert third["saved"] == 1 and third["next_page"] == 5


async def test_daily_budget_counts_failed_requests_and_pause_survives_restart(engine, monkeypatch):
    monkeypatch.setattr(backfill, "fetch_tab_page", AsyncMock(side_effect=[[record(1)], []]))
    detail = AsyncMock(side_effect=CrawlStoppedError("http_429"))
    monkeypatch.setattr(backfill, "fetch_detail", detail)
    first = await backfill.backfill_batch(
        since=SINCE, store=BackfillStore(engine), fetcher_factory=browser
    )
    assert first["status"] == "stopped" and first["today_attempts"] == 1
    await release_cooldown(engine)
    second = await backfill.backfill_batch(store=BackfillStore(engine), fetcher_factory=browser)
    assert second["status"] == "paused" and detail.await_count == 1
    # Explicit resume still cannot exceed the daily cap.
    third = await backfill.backfill_batch(
        resume_paused=True,
        limits=backfill.BackfillLimits(daily=1),
        store=BackfillStore(engine),
        fetcher_factory=browser,
    )
    assert third["status"] == "daily_limit" and detail.await_count == 1


async def test_atomic_finish_preserves_existing_post_and_rolls_back_on_error(engine):
    store = BackfillStore(engine)
    async with store.locked() as acquired:
        assert acquired
        await store.begin_batch(SINCE, 3600, False)
        await store.enqueue_page([record(1)], 1, SINCE)
        item = (await store.pending(1))[0]
        async with engine.begin() as connection:
            await connection.execute(
                text("""
                INSERT INTO posts(source_url,title,cleaned_text,raw_html,extract_status)
                VALUES(:url,'original','old body','raw snapshot','done')
            """),
                {"url": item["url"]},
            )
        assert not await store.finish(item["url"], {"title": "replacement", "content": "new"})
        async with engine.connect() as connection:
            row = (
                await connection.execute(
                    text("SELECT title,cleaned_text,raw_html,extract_status FROM posts")
                )
            ).one()
            assert tuple(row) == ("original", "old body", "raw snapshot", "done")
        assert await store.pending(1) == []
        await store.enqueue_page([record(2)], 2, SINCE)
        url = (await store.pending(1))[0]["url"]
        with pytest.raises(KeyError):
            await store.finish(url, {"content": "missing title"})
        assert len(await store.pending(1)) == 1


async def test_lock_excludes_second_process_and_releases_after_cancellation(engine):
    one, two = BackfillStore(engine), BackfillStore(engine)
    with pytest.raises(asyncio.CancelledError):
        async with one.locked() as acquired:
            assert acquired
            async with two.locked() as second:
                assert not second
            raise asyncio.CancelledError
    async with two.locked() as acquired:
        assert acquired


